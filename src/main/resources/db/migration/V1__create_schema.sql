CREATE TABLE menu_item
(
    id            BIGINT GENERATED ALWAYS AS IDENTITY,
    restaurant_id BIGINT         NOT NULL,
    name          VARCHAR(150)   NOT NULL,
    description   TEXT           NOT NULL,
    price         NUMERIC(10, 2) NOT NULL,
    dine_in_only  BOOLEAN        NOT NULL DEFAULT FALSE, -- Disponibilidade para pedir apenas no Restaurante.
    photo_url     VARCHAR(500),                          -- Foto do prato (como estávamos fazendo um serviço de back-end e a foto não será utilizada, podemos apenas salvar um caminho de onde a foto estaria)

    CONSTRAINT pk_menu_item PRIMARY KEY (id),
    CONSTRAINT ck_menu_item_price CHECK (price >= 0),
    CONSTRAINT fk_menu_item_restaurant FOREIGN KEY (restaurant_id)
        REFERENCES restaurant (id) ON DELETE CASCADE
);
